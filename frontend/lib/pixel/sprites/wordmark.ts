const SPACE_GAP = "..";

/**
 * Compose a sprite string from text. Unknown characters render as a
 * single-pixel space — keeps the renderer total instead of throwing.
 * Letters are joined with a one-column gap; the caller's palette
 * decides the on-pixel color via the key "X".
 */
export function renderWord(text: string): string {
  const upper = text.toUpperCase();
  const rows: string[] = ["", "", "", "", "", "", ""];
  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i] as keyof typeof G;
    const glyph = G[ch] ?? G[" "];
    for (let r = 0; r < 7; r++) {
      // Map "1" → "X" (renderer fills via palette), "0" → "." (transparent).
      const line = glyph[r].replace(/1/g, "X").replace(/0/g, ".");
      rows[r] += (i === 0 ? "" : SPACE_GAP.slice(0, 1)) + line;
    }
  }
  return rows.join("\n");
}

/**
 * Palette for `<PixelSprite sprite={renderWord("...")} palette={wordmarkPalette(c)}>`.
 * `color` is the on-pixel fill; passing a CSS var lets the wordmark inherit
 * the active direction's accent.
 */
export function wordmarkPalette(color: string) {
  return { X: color } as const;
}
